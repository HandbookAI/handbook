/**
 * Renders the three generated configuration surfaces — `.env.example`,
 * `docs/configuration.md`, `handbook.config.example.yaml` — from `SETTINGS`
 * and nothing else, so none of them can say something the registry does not.
 *
 * `scripts/gen-config-docs.mjs` writes what these functions return, and the
 * drift test in `packages/cli` imports the same functions and compares their
 * output to the checked-in files byte for byte. A generator and a checker
 * that could disagree would defeat the point, so every string below must be
 * derived from a `Setting` field — never a hand-typed default, example, or
 * language name.
 *
 * One deliberate exception to "derive everything": `Setting.example` is, by
 * its own doc comment in `types.ts`, a placeholder for `.env.example` only.
 * `renderConfigDocs` and `renderConfigExampleYaml` read `setting.default`
 * exclusively, so a setting with an `example` but no `default` (`source`,
 * `work`, `llmExtraBody`) still shows up there as unset — exactly the
 * pass-through behaviour decisions item 5 asks for, and the same reason
 * `readBatchSize`, `cardDetail` and `proseLang` show up unset too, even
 * though none of those three carries an `example` at all.
 */
import { envName, fileKeyCandidates, scopedEnvName } from './names.js';
import { SETTINGS, settingByKey, settingsFor } from './registry.js';
import type { Setting } from './types.js';

const ALL_COMMANDS: readonly string[] = [...new Set(SETTINGS.flatMap((s) => s.commands))];

/** Escapes a value that lands inside a markdown table cell. */
function escapeCell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

/**
 * The value `.env.example` shows as a placeholder — `example` first (it
 * exists precisely to give a better placeholder than an empty-string or
 * absent default would), then the real default, then nothing at all for a
 * genuine pass-through.
 */
function envDisplayValue(setting: Setting): string | undefined {
  if (setting.example !== undefined) return setting.example;
  if (setting.default !== undefined) return String(setting.default);
  return undefined;
}

/** `llmMaxTokens` → `maxTokens`: the leaf name once the `llm` group owns the prefix. */
function stripLlmPrefix(key: string): string {
  const rest = key.slice(3);
  return rest.length === 0 ? rest : rest.charAt(0).toLowerCase() + rest.slice(1);
}

/**
 * True for the settings that share the literal `llm*` prefix *and* are not
 * scoped to a single command — the one semantic group named in the brief
 * (`llmModel` → `llm: { model }`). A setting scoped to exactly one command
 * (e.g. `llmCache`, generate-only) nests under that command instead; see
 * `renderConfigExampleYaml`.
 */
function isLlmGroupMember(setting: Setting): boolean {
  return /^llm[A-Z]/.test(setting.key) && setting.commands.length > 1;
}

