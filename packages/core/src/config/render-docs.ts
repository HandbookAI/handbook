interface YamlEntry {
  readonly leaf: string;
  readonly setting: Setting;
}

/** Renders a scalar exactly as YAML would read it back. */
function yamlScalar(value: string | number | boolean): string {
  if (typeof value !== 'string') return String(value);
  // Bare is fine for the plain, punctuation-light values every current
  // default happens to be; anything else gets a quoted, JSON-safe fallback
  // rather than risking a value YAML would parse differently than intended.
  return value !== '' && /^[\w./:-]+$/.test(value) ? value : JSON.stringify(value);
}

function requiredNote(setting: Setting, command?: string): string {
  if (command !== undefined) {
    return setting.required || setting.requiredFor?.includes(command) ? ' (required)' : '';
  }
  if (setting.required) return ' (required)';
  if (setting.requiredFor?.length) return ` (required for: ${setting.requiredFor.join(', ')})`;
  return '';
}

export function renderConfigExampleYaml(): string {
  const sections = new Map<string, YamlEntry[]>();
  const flatEntries: YamlEntry[] = [];

  const addTo = (section: string, leaf: string, setting: Setting): void => {
    const entries = sections.get(section) ?? [];
    entries.push({ leaf, setting });
    sections.set(section, entries);
  };

  for (const setting of SETTINGS) {
    // Never a flag, never a config-file key — see file.ts, which throws if
    // one turns up in a real handbook.config.yaml.
    if (setting.secret) continue;

    if (setting.scopedOnly) {
      // The flat key is not a valid lookup for these (see fileKeyCandidates),
      // so every command that shares one gets its own scoped entry.
      for (const command of setting.commands) addTo(command, setting.key, setting);
    } else if (isLlmGroupMember(setting)) {
      addTo('llm', stripLlmPrefix(setting.key), setting);
    } else if (setting.commands.length === 1) {
      addTo(setting.commands[0] as string, setting.key, setting);
    } else {
      flatEntries.push({ leaf: setting.key, setting });
    }
  }

  const lines: string[] = [
    '# Every non-secret setting, nested by command (or by the shared `llm` group).',
    '# Generated by `pnpm run config:docs` — hand-editing this file fails',
    '# packages/cli/src/docs-drift.test.ts, which names the regeneration command.',
    '#',
    '# This file is not auto-loaded (discovery looks for handbook.config.yaml/.yml/.json);',
    '# copy what you need into one of those and edit it. Any key below may also be',
    '# written flat instead of nested — e.g. `llmModel: gpt-4o-mini` instead of',
    '# `llm: { model: gpt-4o-mini }` — both flatten to the exact same setting.',
    '#',
    '# A key shown with a value is its built-in default. A key with no value has none —',
    "# either it's resolved elsewhere (see its comment) or it must be supplied.",
    '',
  ];

  const emit = (entry: YamlEntry, indent: string, command?: string): void => {
    lines.push(`${indent}# ${entry.setting.doc}${requiredNote(entry.setting, command)}`);
    if (entry.setting.default !== undefined) {
      lines.push(`${indent}${entry.leaf}: ${yamlScalar(entry.setting.default)}`);
    } else {
      lines.push(`${indent}# ${entry.leaf}:`);
    }
  };

  for (const entry of flatEntries) emit(entry, '');

  for (const [section, entries] of sections) {
    lines.push('', `${section}:`);
    for (const entry of entries) emit(entry, '  ', section);
  }

  return `${lines.join('\n')}\n`;
}
