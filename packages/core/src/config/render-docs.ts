export function renderEnvExample(): string {
  const lines: string[] = [
    '# Copy to .env (git-ignored) — the `handbook` CLI auto-loads ./.env from the',
    '# directory you run it in. Shell environment variables always win over this file.',
    '#',
    '# --env <name> (or HANDBOOK_ENV) selects a per-environment cascade instead, highest',
    '# precedence first: .env.<name>.local, .env.<name>, .env.local, .env — the first file',
    '# to set a key wins, and the shell still wins over all of them. With no --env and no',
    '# HANDBOOK_ENV, only .env.local and .env load — exactly what loaded before this cascade',
    '# existed, so an existing setup with no .env.local sees no change at all.',
    '#',
    '# Generated by `pnpm run config:docs` from the settings registry — do not hand-edit;',
    '# a hand-edit fails packages/cli/src/docs-drift.test.ts, which names this command as',
    '# the fix. See docs/configuration.md for the full reference.',
  ];

  let groupKey: string | undefined;
  for (const setting of SETTINGS) {
    const thisGroupKey = setting.commands.join(',');
    if (thisGroupKey !== groupKey) {
      lines.push('', `# ── ${setting.commands.join(', ')} ──`);
      groupKey = thisGroupKey;
    }

    lines.push(`# ${setting.doc}`);
    if (setting.secret) {
      lines.push('# secret — must never appear in a config file; set it here or in the shell only');
    }

    const value = envDisplayValue(setting);
    const unsetNote = ' (no default — see the comment above)';

    if (setting.scopedOnly) {
      // Semantics differ per command, so only the scoped name is ever valid;
      // a flat name here would silently be read by nothing.
      for (const command of setting.commands) {
        const name = scopedEnvName(command, setting.key);
        lines.push(value === undefined ? `# ${name}${unsetNote}` : `#${name}=${value}`);
      }
      continue;
    }

    const primary = envName(setting.key);
    const aliases = setting.envAliases ?? [];

    if (setting.secret && aliases.length > 0) {
      // Every line here stays commented, vendor alias included: copying this
      // file to `.env` must not silently supply a placeholder API key. An
      // uncommented `OPENAI_API_KEY=sk-...` would satisfy the client's
      // `if (!apiKey)` guard, trading a clear "no API key" error for a raw
      // 401 from the provider.
      const [vendor, ...rest] = aliases as [string, ...string[]];
      lines.push(value === undefined ? `# ${vendor}${unsetNote}` : `#${vendor}=${value}`);
      lines.push(value === undefined ? `# ${primary}${unsetNote}` : `#${primary}=${value}`);
      for (const alias of rest) {
        lines.push(value === undefined ? `# ${alias}${unsetNote}` : `#${alias}=${value}`);
      }
    } else {
      lines.push(value === undefined ? `# ${primary}${unsetNote}` : `#${primary}=${value}`);
      for (const alias of aliases) {
        lines.push(value === undefined ? `# ${alias}${unsetNote}` : `#${alias}=${value}`);
      }
    }
  }

  return `${lines.join('\n')}\n`;
}

