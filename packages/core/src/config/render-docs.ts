function typeCell(setting: Setting): string {
  if (setting.type !== 'enum') return setting.type;
  if (setting.dynamicChoices === 'languages') {
    // The adapter registry lives in @handbook/analyzer, which this package
    // must not depend on — so the choice list is described, not enumerated.
    return 'enum (`auto`, plus any registered language)';
  }
  return `enum (${escapeCell((setting.choices ?? []).join('|'))})`;
}

function defaultCell(setting: Setting, command: string): string {
  if (setting.default !== undefined) {
    // A bare pair of backticks around an empty string (llmApiKey's default)
    // is an ambiguous, easy-to-misrender GFM construct — show the emptiness
    // instead of hiding it in whitespace no reader can see.
    const text = String(setting.default);
    return text === '' ? '`""` (empty)' : `\`${escapeCell(text)}\``;
  }
  if (setting.required || setting.requiredFor?.includes(command)) return 'required';
  return '—';
}

function envCell(command: string, setting: Setting): string {
  if (setting.scopedOnly) return `\`${scopedEnvName(command, setting.key)}\` *(scoped)*`;
  const names = [envName(setting.key), ...(setting.envAliases ?? [])];
  return names.map((n) => `\`${n}\``).join(', ');
}

function row(command: string, setting: Setting): string {
  const cells = [
    `\`${setting.key}\``,
    setting.flag ? `\`${setting.flag}\`` : '—',
    envCell(command, setting),
    typeCell(setting),
    defaultCell(setting, command),
    escapeCell(setting.doc),
  ];
  return `| ${cells.join(' | ')} |`;
}

